func TestCopyDistributedFinalRowWithoutNewline(t *testing.T) {
	frontend, conn, err := bootstrapConnection(t)
	assert.NoError(t, err, "startup failed")
	defer func() {
		_ = conn.Close()
	}()

	begin := MessageGroup{
		Request: []pgproto3.FrontendMessage{
			&pgproto3.Query{String: "BEGIN"},
			&pgproto3.Query{String: "SELECT 1 /* __spqr__execute_on: sh4 */"},
		},
		Response: []pgproto3.BackendMessage{
			&pgproto3.CommandComplete{CommandTag: []byte("BEGIN")},
			&pgproto3.ReadyForQuery{TxStatus: byte(txstatus.TXACT)},
			&pgproto3.RowDescription{Fields: []pgproto3.FieldDescription{{
				Name:         []byte("?column?"),
				DataTypeOID:  23,
				DataTypeSize: 4,
				TypeModifier: -1,
			}}},
			&pgproto3.DataRow{Values: [][]byte{[]byte("1")}},
			&pgproto3.CommandComplete{CommandTag: []byte("SELECT 1")},
			&pgproto3.ReadyForQuery{TxStatus: byte(txstatus.TXACT)},
		},
	}

	rollback := MessageGroup{
		Request: []pgproto3.FrontendMessage{
			&pgproto3.Query{String: "ROLLBACK"},
		},
		Response: []pgproto3.BackendMessage{
			&pgproto3.CommandComplete{CommandTag: []byte("ROLLBACK")},
			&pgproto3.ReadyForQuery{TxStatus: byte(txstatus.TXIDLE)},
		},
	}

	copySimple := MessageGroup{
		Request: []pgproto3.FrontendMessage{
			&pgproto3.Query{String: "COPY t(id) FROM STDIN"},
			&pgproto3.CopyData{Data: []byte("2102\n2103")},
			&pgproto3.CopyDone{},
		},
		Response: []pgproto3.BackendMessage{
			&pgproto3.CopyInResponse{ColumnFormatCodes: []uint16{0}},
			&pgproto3.CommandComplete{},
			&pgproto3.ReadyForQuery{TxStatus: byte(txstatus.TXACT)},
		},
		SkipCheckCommandTag: true,
	}

	copyExtended := MessageGroup{
		Request: []pgproto3.FrontendMessage{
			&pgproto3.Parse{Query: "COPY t(id) FROM STDIN"},
			&pgproto3.Bind{PreparedStatement: ""},
			&pgproto3.Execute{},
			&pgproto3.CopyData{Data: []byte("2102\n2103")},
			&pgproto3.CopyDone{},
			&pgproto3.Sync{},
		},
		Response: []pgproto3.BackendMessage{
			&pgproto3.ParseComplete{},
			&pgproto3.BindComplete{},
			&pgproto3.CopyInResponse{ColumnFormatCodes: []uint16{0}},
			&pgproto3.CommandComplete{},
			&pgproto3.ReadyForQuery{TxStatus: byte(txstatus.TXACT)},
		},
		SkipCheckCommandTag: true,
	}

	protoTestRunner(t, frontend, []MessageGroup{
		begin,
		copySimple,
		rollback,
		begin,
		copyExtended,
		rollback,
	})
}

