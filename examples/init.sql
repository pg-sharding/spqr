CREATE DISTRIBUTION ds1 COLUMN TYPES integer;

CREATE DISTRIBUTED RELATION users DISTRIBUTION KEY id IN ds1;
CREATE DISTRIBUTED RELATION user_addresses DISTRIBUTION KEY user_id IN ds1;
CREATE DISTRIBUTED RELATION orders DISTRIBUTION KEY user_id IN ds1;
CREATE DISTRIBUTED RELATION order_items DISTRIBUTION KEY user_id IN ds1;
CREATE DISTRIBUTED RELATION payments DISTRIBUTION KEY user_id IN ds1;
CREATE DISTRIBUTED RELATION shopping_carts DISTRIBUTION KEY user_id IN ds1;

CREATE REFERENCE TABLE countries;
CREATE REFERENCE TABLE product_categories;
CREATE REFERENCE TABLE products;
CREATE REFERENCE TABLE currencies;

-- Automatically route [0, 50000) to sh1 and [50000, +infinity) to sh2
CREATE KEY RANGES FOR DISTRIBUTION ds1 BETWEEN 0 AND 100000 USING SHARDS sh2, sh1;
